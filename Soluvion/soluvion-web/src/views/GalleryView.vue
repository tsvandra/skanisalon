<script setup>
  import { ref, inject, watch, nextTick, computed } from 'vue';
  import api from '@/services/api';
  import { useAutoSaveQueue } from '@/composables/useAutoSaveQueue';
  import { useImageUpload } from '@/composables/useImageUpload';
  import { useDragAndDrop } from '@/composables/useDragAndDrop';
  import { useTranslation } from '@/composables/useTranslation';
  import draggable from 'vuedraggable';
  import { useI18n } from 'vue-i18n';
  import { compressImage } from '@/utils/imageCompressor';

  const { t, locale } = useI18n();
  const isLoggedIn = inject('isLoggedIn');

  const currentLang = computed(() => locale.value);

  const images = ref([]);
  const categories = ref([]);
  const groupedImages = ref([]);
  const isLoading = ref(false);
  const showPreview = ref(false);
  const fileInputRef = ref(null);
  const currentUploadCategory = ref(null);
  const categoryInputRefs = ref({});
  const company = inject('company', ref(null));

  const previewImage = ref(null);
  const previewList = ref([]);
  const previewIndex = ref(0);
  const touchStartX = ref(0);
  const touchEndX = ref(0);

  const expandedCategoryId = ref(null);
  const transitionName = ref('fade');

  // --- ÚJ: Globális Oldal Beállítások, Egyedi Kép Beállítások & Jelmagyarázat ---
  const isGlobalEditMode = ref(false);
  const showLegendHelp = ref(false);
  const editingImage = ref(null);
  const editingImageCategoryId = ref(null);
  const collapsedEditCategories = ref({});

  const areAllCategoriesCollapsed = computed(() => {
    const validGroups = groupedImages.value.filter(g => g.id !== -1);
    return validGroups.length > 0 && validGroups.every(g => !!collapsedEditCategories.value[g.id]);
  });

  const toggleEditCategoryCollapse = (groupId) => {
    collapsedEditCategories.value = {
      ...collapsedEditCategories.value,
      [groupId]: !collapsedEditCategories.value[groupId]
    };
  };

  const toggleCollapseAllCategories = () => {
    const targetState = !areAllCategoriesCollapsed.value;
    const nextMap = {};
    groupedImages.value.forEach(g => {
      nextMap[g.id] = targetState;
    });
    collapsedEditCategories.value = nextMap;
  };

  const moveCategoryStep = async (groupId, delta) => {
    const idx = groupedImages.value.findIndex(g => g.id === groupId);
    if (idx === -1) return;
    const targetIdx = idx + delta;
    if (targetIdx < 0 || targetIdx >= groupedImages.value.length) return;
    if (groupedImages.value[targetIdx].id === -1) return;

    const [moved] = groupedImages.value.splice(idx, 1);
    groupedImages.value.splice(targetIdx, 0, moved);
    await onCategoryDragChange();
  };

  const { addToQueue } = useAutoSaveQueue();
  const { isUploading, uploadImage } = useImageUpload();
  const { reorderNestedItems, reorderFlatItems } = useDragAndDrop();
  const { translatingField, translateField } = useTranslation();

  const ensureDict = (field, defaultValue = "") => {
    if (field && typeof field === 'object' && field !== null) return field;
    return { [currentLang.value]: field || defaultValue };
  };

  const getOptimizedUrl = (url, width = 'auto') => {
    if (!url) return '';
    if (!url.includes('cloudinary.com') || url.includes('f_auto')) return url;
    const parts = url.split('/upload/');
    if (parts.length === 2) {
      return `${parts[0]}/upload/f_auto,q_auto,w_${width},c_limit/${parts[1]}`;
    }
    return url;
  };

  const triggerTranslation = async (obj, fieldName) => {
    await translateField({
      obj,
      fieldName,
      targetLang: currentLang.value,
      defaultLang: company.value?.defaultLanguage || 'hu',
      loadingKey: `${obj.id || 'new'}-${fieldName}-${currentLang.value}`,
      onSuccess: (updatedObj) => {
        if (updatedObj.items) saveCategory(updatedObj);
        else saveImage(updatedObj);
      }
    });
  };

  const isAutoGeneratedFilename = (text) => {
    if (!text || typeof text !== 'string') return false;
    const trimmed = text.trim();
    if (!trimmed) return false;
    return /^(Messenger_creation|Screenshot_|IMG_|DSC_|PXL_|received_|inbound|image\d*|photo\d*|\d{8}_\d+)/i.test(trimmed)
      || /\.(jpe?g|png|webp|heic|gif|bmp|avif)$/i.test(trimmed);
  };

  const ensureCleanTitleDict = (field) => {
    const dict = ensureDict(field, "");
    const cleaned = {};
    for (const [k, v] of Object.entries(dict)) {
      cleaned[k] = isAutoGeneratedFilename(v) ? "" : (v || "");
    }
    return cleaned;
  };

  const getDisplayTitle = (img) => {
    const val = img?.title?.[currentLang.value];
    if (!val || isAutoGeneratedFilename(val)) return '';
    return val.trim();
  };

  const fetchData = async () => {
    isLoading.value = true;
    try {
      const timestamp = new Date().getTime();
      const [resCats, resImages] = await Promise.all([
        api.get(`/api/Gallery/categories?t=${timestamp}`),
        api.get(`/api/Gallery?t=${timestamp}`)
      ]);

      const rawCats = Array.isArray(resCats.data) ? resCats.data : [];
      const rawImages = Array.isArray(resImages.data) ? resImages.data : [];

      categories.value = rawCats.map(c => ({ ...c, name: ensureDict(c.name, t('gallery.untitled')) }));
      images.value = rawImages.map(i => ({
        ...i,
        category: ensureDict(i.category, "Egyéb"),
        title: ensureCleanTitleDict(i.title)
      }));

      buildNestedStructure();
    } catch (error) { console.error("Hiba:", error); }
    finally { isLoading.value = false; }
  };

  const buildNestedStructure = () => {
    const groups = [];
    const groupsMap = new Map();
    categories.value.forEach(cat => {
      const group = { id: cat.id, name: cat.name, items: [], orderIndex: cat.orderIndex };
      groups.push(group);
      groupsMap.set(cat.id, group);
    });
    const uncategorized = { id: -1, name: { [currentLang.value]: t('gallery.uncategorized') }, items: [], orderIndex: 999999 };

    images.value.forEach(img => {
      if (img.categoryId && groupsMap.has(img.categoryId)) {
        groupsMap.get(img.categoryId).items.push(img);
      } else {
        uncategorized.items.push(img);
      }
    });

    groups.forEach(g => g.items.sort((a, b) => (a.orderIndex || 0) - (b.orderIndex || 0)));
    if (uncategorized.items.length > 0) groups.push(uncategorized);
    groupedImages.value = groups;
  };

  watch(() => company?.value?.id, (newId) => { if (newId) fetchData(); }, { immediate: true });

  const createCategory = async () => {
    if (!isLoggedIn.value) return;
    try {
      const res = await api.post('/api/Gallery/categories', { name: { [currentLang.value]: t('gallery.newGalleryName') } });
      const newCat = res.data;
      newCat.name = ensureDict(newCat.name);
      categories.value.unshift(newCat);
      const newGroup = { id: newCat.id, name: newCat.name, items: [], orderIndex: newCat.orderIndex };
      groupedImages.value.unshift(newGroup);
      await nextTick();
      if (categoryInputRefs.value[newGroup.id]) categoryInputRefs.value[newGroup.id].focus();
    } catch (err) { console.error(err); }
  };

  const saveCategory = (group) => {
    if (!group.id || group.id === -1) return;
    if (!group.name[currentLang.value]?.trim()) group.name[currentLang.value] = t('gallery.newGalleryName');
    addToQueue(`cat-${group.id}`, async () => {
      await api.put(`/api/Gallery/categories/${group.id}`, { name: group.name, orderIndex: group.orderIndex });
    });
  };

  const deleteCategory = async (group) => {
    if (!confirm(t('gallery.confirmDeleteCategory', { name: group.name[currentLang.value] }))) return;
    try {
      await api.delete(`/api/Gallery/categories/${group.id}`);
      groupedImages.value = groupedImages.value.filter(g => g.id !== group.id);
      categories.value = categories.value.filter(c => c.id !== group.id);
    } catch (err) { alert(t('gallery.deleteFailed')); }
  };

  const saveImage = (img) => {
    addToQueue(img.id, async () => {
      await api.put(`/api/Gallery/${img.id}`, {
        id: img.id,
        title: img.title,
        categoryId: img.categoryId,
        categoryName: img.category,
        orderIndex: img.orderIndex
      });
    });
  };

  const onCategoryDragChange = async () => {
    await reorderFlatItems(groupedImages.value.filter(g => g.id !== -1), saveCategory);
  };

  const onImageDragChange = async () => {
    await reorderNestedItems(groupedImages.value, 'items', saveImage, (img, group) => {
      if (img.categoryId !== group.id) {
        img.categoryId = group.id;
        img.category = JSON.parse(JSON.stringify(group.name));
        return true;
      }
      return false;
    });
  };

  const openImageSettings = (img, group) => {
    editingImage.value = img;
    editingImageCategoryId.value = group?.id ?? img.categoryId;
  };

  const onMoveImageCategory = async () => {
    if (!editingImage.value || !editingImageCategoryId.value) return;
    const targetGroupId = Number(editingImageCategoryId.value);
    if (editingImage.value.categoryId === targetGroupId) return;

    const targetGroup = groupedImages.value.find(g => g.id === targetGroupId);
    if (!targetGroup) return;

    // Eltávolítás a régi csoportból
    groupedImages.value.forEach(g => {
      const idx = g.items.findIndex(i => i.id === editingImage.value.id);
      if (idx !== -1) g.items.splice(idx, 1);
    });

    // Áthelyezés az új csoportba
    editingImage.value.categoryId = targetGroup.id;
    editingImage.value.category = JSON.parse(JSON.stringify(targetGroup.name));
    targetGroup.items.push(editingImage.value);

    saveImage(editingImage.value);
  };

  const deleteImage = async (id) => {
    if (!confirm(t('gallery.confirmDeleteImage'))) return;
    try {
      if (editingImage.value?.id === id) {
        editingImage.value = null;
      }
      images.value = images.value.filter(i => i.id !== id);
      buildNestedStructure();
      await api.delete(`/api/Gallery/${id}`);
    } catch (error) { fetchData(); }
  };

  const triggerCategoryUpload = (group) => {
    currentUploadCategory.value = group;
    if (fileInputRef.value) fileInputRef.value.click();
  };

  const handleFiles = async (event) => {
    const files = event.target.files;
    if (!files || files.length === 0 || !currentUploadCategory.value) return;
    for (let i = 0; i < files.length; i++) {
      try {
        const compressed = await compressImage(files[i], { maxWidth: 1920, maxHeight: 1920, quality: 0.85 });
        await uploadImage(compressed, '/api/Gallery', { categoryId: currentUploadCategory.value.id });
      }
      catch (err) { console.error("Hiba:", err); }
    }
    await fetchData();
    currentUploadCategory.value = null;
    event.target.value = "";
  };

  // --- OKOS GALÉRIA FUNKCIÓK UX JAVÍTÁSSAL ---

  const toggleCategory = (id) => {
    const isOpening = expandedCategoryId.value !== id;
    expandedCategoryId.value = isOpening ? id : null;

    // Ha kinyitunk egy kategóriát, odagörgetünk hozzá
    if (isOpening) {
      setTimeout(() => {
        const catEl = document.getElementById(`cat-${id}`);
        if (catEl) {
          catEl.scrollIntoView({ behavior: 'smooth', block: 'start' });
        }
      }, 350);
    }
  };

  const getVisibleGroupItems = (group) => {
    if (isLoggedIn.value && isGlobalEditMode.value) return group.items;
    if (expandedCategoryId.value === group.id) return group.items;
    // Összecsukott előnézetben 1 teljes sort adunk vissza (mobilon 3, tableten 4, asztali gépen 5 kép tölti ki a sort)
    return group.items.slice(0, 5);
  };

  const getCollapsedItemVisibilityClass = (group, index) => {
    if (expandedCategoryId.value === group.id) return 'flex';
    if (index === 3) return 'hidden sm:flex';
    if (index === 4) return 'hidden md:flex';
    return 'flex';
  };

  const openPreview = (img, index, items, groupId) => {
    if ((!isLoggedIn.value || !isGlobalEditMode.value) && groupId && expandedCategoryId.value !== groupId) {
      toggleCategory(groupId);
    }

    previewList.value = items;
    previewIndex.value = index;
    previewImage.value = img;
    transitionName.value = 'fade';
    showPreview.value = true;
  };

  const nextImage = () => {
    if (previewIndex.value < previewList.value.length - 1) {
      transitionName.value = 'slide-next';
      previewIndex.value++;
      previewImage.value = previewList.value[previewIndex.value];
    }
  };

  const prevImage = () => {
    if (previewIndex.value > 0) {
      transitionName.value = 'slide-prev';
      previewIndex.value--;
      previewImage.value = previewList.value[previewIndex.value];
    }
  };

  const handleTouchStart = (e) => { touchStartX.value = e.changedTouches[0].screenX; };
  const handleTouchEnd = (e) => {
    touchEndX.value = e.changedTouches[0].screenX;
    if (touchStartX.value - touchEndX.value > 40) nextImage();
    if (touchEndX.value - touchStartX.value > 40) prevImage();
  };

  const closePreview = () => {
    showPreview.value = false;

    setTimeout(() => {
      const thumbEl = document.getElementById(`thumb-${previewImage.value?.id}`);
      if (thumbEl) {
        thumbEl.scrollIntoView({ behavior: 'smooth', block: 'center' });

        thumbEl.classList.add('ring-4', 'ring-primary', 'scale-[1.03]', 'z-10');
        setTimeout(() => {
          thumbEl.classList.remove('ring-4', 'ring-primary', 'scale-[1.03]', 'z-10');
        }, 1000);
      }
    }, 50);
  };
</script>

<template>
  <div class="max-w-5xl w-full mx-auto px-2.5 sm:px-4 py-4 md:p-8 box-border text-text overflow-x-hidden">

    <!-- FEJLÉC: Cím + Adminban Jelmagyarázat (💡) és Oldal beállítások (⚙️) gomb -->
    <div class="flex flex-col gap-3 sm:gap-4 mb-6 md:mb-8 border-b border-text/10 pb-4">
      <div class="flex flex-wrap justify-between items-center gap-2.5">
        <h2 class="text-primary m-0 font-light tracking-wide sm:tracking-widest text-2xl sm:text-3xl">
          {{ (isLoggedIn && isGlobalEditMode) ? $t('gallery.editorTitle') : $t('gallery.title') }}
        </h2>

        <div v-if="isLoggedIn" class="flex items-center gap-2 flex-wrap">
          <!-- 💡 Jelmagyarázat gomb -->
          <button type="button"
                  @click="showLegendHelp = true"
                  class="px-3 py-2 min-h-[38px] sm:min-h-[42px] rounded-xl border border-primary/35 bg-primary/10 text-primary hover:bg-primary/20 font-semibold text-xs sm:text-sm flex items-center gap-1.5 cursor-pointer transition-all shadow-xs">
            <i class="pi pi-lightbulb text-xs sm:text-sm"></i>
            <span>{{ $t('gallery.helpLegendBtn') }}</span>
          </button>

          <!-- ⚙️ Globális / Oldal beállítások kapcsoló gomb -->
          <button type="button"
                  @click="isGlobalEditMode = !isGlobalEditMode"
                  class="px-3.5 py-2 min-h-[38px] sm:min-h-[42px] rounded-xl border font-bold text-xs sm:text-sm flex items-center gap-1.5 cursor-pointer transition-all shadow-xs"
                  :class="isGlobalEditMode
                    ? 'bg-primary text-black border-primary shadow-md'
                    : 'bg-surface text-text border-text/15 hover:border-primary/50 hover:text-primary'">
            <i class="pi pi-cog text-xs sm:text-sm" :class="{ 'animate-spin-slow': isGlobalEditMode }"></i>
            <span>{{ isGlobalEditMode ? $t('gallery.globalSettingsActive') : $t('gallery.globalSettingsBtn') }}</span>
          </button>
        </div>
      </div>

      <!-- GLOBÁLIS ESZKÖZTÁR (Csak akkor látszik, ha az ⚙️ Oldal beállítások aktív) -->
      <div v-if="isLoggedIn && isGlobalEditMode"
           class="bg-surface border border-primary/30 rounded-2xl p-3 sm:p-4 shadow-md flex flex-wrap items-center justify-between gap-2.5 animate-fade-in">
        <div class="flex items-center gap-2 text-xs sm:text-sm text-text-muted flex-1 min-w-[200px]">
          <i class="pi pi-arrows-alt text-primary shrink-0"></i>
          <span>{{ $t('gallery.helpDragDesc') }}</span>
        </div>

        <div class="flex flex-wrap items-center gap-2 w-full sm:w-auto">
          <!-- Összes mappa összecsukása / kinyitása a könnyű sorrend-állításhoz -->
          <button type="button"
                  @click="toggleCollapseAllCategories"
                  class="flex-1 sm:flex-initial bg-background text-text border border-text/20 hover:border-primary/50 hover:text-primary font-semibold flex justify-center items-center gap-2 rounded-xl transition-all px-3.5 py-2 min-h-[40px] cursor-pointer text-xs sm:text-sm">
            <i class="pi text-xs" :class="areAllCategoriesCollapsed ? 'pi-angle-double-down text-primary' : 'pi-angle-double-up text-primary'"></i>
            <span>{{ areAllCategoriesCollapsed ? $t('gallery.expandAllCategories') : $t('gallery.collapseAllCategories') }}</span>
          </button>

          <button @click="createCategory"
                  class="flex-1 sm:flex-initial bg-primary text-black font-bold flex justify-center items-center gap-2 rounded-xl transition-all hover:brightness-95 px-4 py-2 min-h-[40px] border-none cursor-pointer shadow-sm text-xs sm:text-sm shrink-0">
            <i class="pi pi-plus-circle"></i> {{ $t('gallery.newGallery') }}
          </button>
        </div>
      </div>

      <input type="file" ref="fileInputRef" @change="handleFiles" multiple accept="image/*" class="hidden" />
    </div>

    <div v-if="isLoading" class="text-text-muted flex items-center min-h-[44px]">
      <i class="pi pi-spin pi-spinner mr-2 text-xl"></i> {{ $t('common.loading') }}
    </div>

    <draggable v-else
               v-model="groupedImages"
               group="categories"
               item-key="id"
               handle=".drag-handle-cat"
               @change="onCategoryDragChange"
               :disabled="!isLoggedIn || !isGlobalEditMode">
      <template #item="{ element: group, index: groupIndex }">
        <div :id="`cat-${group.id}`"
             class="bg-surface border border-text/10 rounded-2xl shadow-sm scroll-mt-24 transition-all"
             :class="isLoggedIn && isGlobalEditMode && collapsedEditCategories[group.id] ? 'mb-2.5 p-2 sm:p-2.5' : 'mb-6 sm:mb-8 p-2.5 sm:p-4 md:p-5'">

          <!-- KATEGÓRIA FEJLÉC -->
          <div class="flex flex-wrap justify-between items-center px-3 py-2.5 sm:px-4 sm:py-3 bg-text/5 rounded-xl border border-text/5 gap-2.5 transition-colors duration-200"
               :class="[
                 (!isLoggedIn || !isGlobalEditMode) ? 'cursor-pointer hover:bg-text/10 mb-3 sm:mb-4' : '',
                 (isLoggedIn && isGlobalEditMode && !collapsedEditCategories[group.id]) ? 'mb-3 sm:mb-4' : ''
               ]"
               @click="(!isLoggedIn || !isGlobalEditMode) && toggleCategory(group.id)">

            <div class="flex items-center gap-2 flex-1 min-w-0">
              <div v-if="isLoggedIn && isGlobalEditMode && group.id !== -1"
                   class="cursor-grab text-xl sm:text-2xl text-primary flex items-center justify-center min-w-[32px] min-h-[36px] hover:text-primary/80 drag-handle-cat transition-colors shrink-0 touch-none"
                   :title="$t('gallery.moveGallery')">⋮⋮</div>

              <!-- Szerkesztőmódban input + fordító gomb -->
              <template v-if="isLoggedIn && isGlobalEditMode && group.id !== -1">
                <div class="flex items-center gap-1.5 flex-1 min-w-0">
                  <input :ref="el => categoryInputRefs[group.id] = el"
                         v-model="group.name[currentLang]"
                         @change="saveCategory(group)"
                         @click.stop
                         class="bg-background/60 border border-primary/30 text-primary text-base sm:text-lg md:text-xl font-bold py-1.5 px-2.5 flex-1 min-w-0 focus:outline-none focus:border-primary transition-all rounded-lg truncate"
                         :placeholder="$t('gallery.newGalleryName')" />

                  <button @click.stop="triggerTranslation(group, 'name')"
                          class="bg-primary/10 border border-primary/30 rounded-lg text-primary cursor-pointer flex items-center justify-center min-w-[36px] min-h-[36px] transition-all hover:bg-primary/20 shrink-0"
                          :title="$t('gallery.translate')">
                    <i v-if="translatingField === `${group.id}-name-${currentLang}`" class="pi pi-spin pi-spinner"></i>
                    <i v-else class="pi pi-sparkles"></i>
                  </button>

                  <span class="text-text-muted text-sm font-bold shrink-0 select-none ml-1">({{ group.items.length }})</span>
                </div>
              </template>

              <!-- Tiszta nézetben a cím és a darabszám közvetlenül egymás mellett a bal oldalon, a nyíl pedig a jobb szélen -->
              <template v-else>
                <div class="flex items-center gap-2 min-w-0">
                  <h3 class="text-primary text-base sm:text-lg md:text-xl font-bold py-0.5 m-0 truncate select-none">
                    {{ group.id === -1 ? $t('gallery.uncategorized') : group.name[currentLang] }}
                  </h3>
                  <span class="text-text-muted text-sm sm:text-base font-semibold shrink-0 select-none">
                    ({{ group.items.length }})
                  </span>
                </div>

                <i v-if="group.items.length > 3"
                   :class="expandedCategoryId === group.id ? 'pi pi-chevron-up' : 'pi pi-chevron-down'"
                   class="text-primary ml-auto text-base sm:text-lg transition-transform duration-300 shrink-0"></i>
              </template>
            </div>

            <!-- Kategória műveletek (Fel/Le léptetés + Feltöltés ide + Üres mappa törlése + Mappa összecsukása/kinyitása) -->
            <div v-if="isLoggedIn && isGlobalEditMode && group.id !== -1" class="flex items-center gap-1.5 sm:gap-2 w-full sm:w-auto justify-end" @click.stop>
              <!-- Gyors Fel / Le sorrend-léptető gombok -->
              <div class="inline-flex items-center rounded-xl border border-text/15 bg-background overflow-hidden shrink-0">
                <button type="button"
                        @click.stop="moveCategoryStep(group.id, -1)"
                        :disabled="groupIndex === 0"
                        class="w-8 h-[36px] flex items-center justify-center text-text-muted hover:text-primary hover:bg-text/5 disabled:opacity-30 cursor-pointer border-none bg-transparent transition-colors">
                  <i class="pi pi-arrow-up text-xs"></i>
                </button>
                <button type="button"
                        @click.stop="moveCategoryStep(group.id, 1)"
                        :disabled="groupIndex >= groupedImages.filter(g => g.id !== -1).length - 1"
                        class="w-8 h-[36px] flex items-center justify-center text-text-muted hover:text-primary hover:bg-text/5 disabled:opacity-30 cursor-pointer border-left border-text/10 bg-transparent transition-colors">
                  <i class="pi pi-arrow-down text-xs"></i>
                </button>
              </div>

              <button @click.stop="triggerCategoryUpload(group)"
                      class="bg-background text-primary border border-primary/35 px-3 py-1.5 min-h-[36px] font-bold text-xs sm:text-sm rounded-xl flex items-center justify-center gap-1.5 cursor-pointer transition-colors hover:bg-primary hover:text-black shadow-xs flex-1 sm:flex-initial"
                      :disabled="isUploading">
                <i v-if="isUploading && currentUploadCategory?.id === group.id" class="pi pi-spin pi-spinner"></i>
                <i v-else class="pi pi-cloud-upload"></i>
                <span>{{ $t('gallery.uploadHere') }}</span>
              </button>

              <button v-if="group.items.length === 0"
                      @click.stop="deleteCategory(group)"
                      class="bg-red-500/10 border border-red-500/30 text-red-500 rounded-xl cursor-pointer flex items-center justify-center min-w-[36px] min-h-[36px] transition-colors hover:bg-red-500 hover:text-white shrink-0"
                      :title="$t('gallery.deleteCategoryBtn')">
                <i class="pi pi-trash text-sm"></i>
              </button>

              <!-- Mappa teljes összecsukása / kinyitása gomb szerkesztőmódban -->
              <button type="button"
                      @click.stop="toggleEditCategoryCollapse(group.id)"
